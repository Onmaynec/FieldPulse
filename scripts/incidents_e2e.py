"""Real browser incident acknowledgement and operator/engineer isolation."""
import os
import subprocess

from playwright.sync_api import expect, sync_playwright

ROOT = os.getenv("SMOKE_URL", "http://127.0.0.1:8000")
PASSWORD = os.getenv("DEMO_PASSWORD", "FieldPulseDemo!2026")


def log_in(page, email):
    page.goto(ROOT, wait_until="domcontentloaded")
    expect(page.locator("#login")).to_be_visible(timeout=15000)
    page.locator('#login-form [name="email"]').fill(email)
    page.locator('#login-form [name="password"]').fill(PASSWORD)
    page.locator('#login-form button[type="submit"]').click()
    expect(page.locator("#shell")).to_be_visible(timeout=20000)


def main():
    # The CI Compose environment is disposable. No synthetic incident is
    # generated by the product on behalf of a user.
    subprocess.run(["docker", "compose", "exec", "-T", "api",
                    "python", "-m", "scripts.incident_seed"], check=True)
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        ctx = browser.new_context(viewport={"width": 1300, "height": 850})
        page = ctx.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        log_in(page, "dispatcher@fieldpulse.local")
        page.locator('.nav-item[data-page="reports"]').click()
        expect(page.locator("#incident-center")).to_be_visible(timeout=20000)
        expect(page.locator("#incident-center .incident-entry")).to_have_count(1, timeout=15000)
        button = page.locator('[data-ack-incident]').first
        expect(button).to_be_visible()
        button.click()
        expect(page.locator("#incident-center")).to_contain_text("Подтверждён оператором", timeout=15000)
        assert page.evaluate("() => state.incidentSummary.unacknowledged") >= 0
        page.locator('[data-refresh-worker]').first.click()
        expect(page.locator("#incident-center")).to_be_visible()
        assert not errors, errors
        ctx.close()
        browser.close()
    print("Incidents E2E: authenticated incident view, acknowledgement and refresh — OK")


if __name__ == "__main__":
    main()
